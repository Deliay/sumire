/**
 * 将 Markdown 文本精简为单行纯文本。
 * 去除标题/引用/列表/任务框等块级标记与链接/粗体/斜体/行内代码等行内标记，
 * 并把换行与连续空白折叠为单个空格。供幻灯片页头等需要「单行省略」的展示用。
 */
export function toSingleLinePlainText(markdown: string): string {
  return markdown
    // 图片：保留 alt 文本
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
    // 链接：保留链接文本，丢弃 URL
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    // 行首块级标记：标题 #、引用 >、无序列表 - * +、有序列表、任务框、分隔线
    .replace(
      /^\s{0,3}(?:#{1,6}[ \t]+|>+[ \t]*|[-*+][ \t]+|\d+[.)][ \t]+|\[[ xX]\][ \t]+|[-*_]{3,}[ \t]*$)/gm,
      "",
    )
    // 行内标记：粗体/斜体/删除线/行内代码（不区分位置，保守去除）
    .replace(/[*_`~]{1,3}/g, "")
    // 任务框勾选标记（可能在列表符号被去除后仍遗留）
    .replace(/\[[ xX]\][ \t]*/g, "")
    // 换行与连续空白折叠为单个空格
    .replace(/\s+/g, " ")
    .trim();
}